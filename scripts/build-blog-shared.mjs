// Bundles the voice files and the guide list into the blog Edge Functions.
// Edge Functions can't read repo files at runtime, so run this before deploying:
//   node scripts/build-blog-shared.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..');
const out = path.join(root, 'supabase', 'functions', '_shared');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const voice = {
  ANTI_SLOP: read('content/voice/Anti_AI_slop.md'),
  MY_TERMS: read('content/voice/my-terms.md'),
  MY_TAKES: read('content/voice/my-takes.md'),
};
fs.writeFileSync(
  path.join(out, 'voice.ts'),
  '// Generated by scripts/build-blog-shared.mjs from content/voice/. Do not edit.\n' +
    Object.entries(voice).map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};\n`).join('')
);

// slug + question from src/content/guides.ts (each guide lists slug, title, question in order)
const src = read('src/content/guides.ts');
const guides = [...src.matchAll(/slug: '([a-z0-9-]+)',\s*\n\s*title: '([^']+)',\s*\n\s*question: '([^']+)'/g)].map(
  ([, slug, title, question]) => ({ slug, title, question })
);
fs.writeFileSync(
  path.join(out, 'guides.ts'),
  '// Generated by scripts/build-blog-shared.mjs from src/content/guides.ts. Do not edit.\n' +
    `export const GUIDES: { slug: string; title: string; question: string }[] = ${JSON.stringify(guides, null, 2)};\n`
);
console.log(`voice files: ${Object.keys(voice).length}, guides: ${guides.length}`);
